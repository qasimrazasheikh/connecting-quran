// Bundles the whole Quran into assets/quran/ so the app reads offline: Arabic (Indo-Pak + QPC Hafs), word-by-word,
// Urdu (Jalandhry) and English (Saheeh), and the grammar from ../data/morph. Each surah is a separate .dat asset file
// (read on demand, kept out of the JS bundle); index.json maps Mushaf pages and juz starts; search.dat holds the text
// search needs; fatihah.json is bundled for
// the Bismillah and the settings preview; src/lib/quran-files.ts lists the files for Metro.
// Run from mobile/: node scripts/fetch-quran.mjs (already-fetched surahs are skipped, so a failed run can just be repeated)
import fs from 'node:fs';
import path from 'node:path';

const SURAHS = Array.from({length: 114}, (_, i) => i + 1);
const OUT = path.resolve('assets/quran');
const ROOT = path.resolve('..');
for (const d of ['surah', 'morph']) fs.mkdirSync(path.join(OUT, d), {recursive: true});

/** JSON from a URL, retried with a growing pause (the sources rate-limit bursts). */
async function get(u, tries = 5){
  for (let i = 1; ; i++){
    try{ const r = await fetch(u); if (!r.ok) throw new Error(`${r.status} ${u}`); return await r.json(); }
    catch(e){ if (i >= tries) throw e; await new Promise(res => setTimeout(res, 1500 * i)); }
  }
}

/** All verses of a surah from quran.com, words included, in one word-translation language. */
async function verses(s, lang){
  const out = [];
  for (let page = 1; ; page++){
    const d = await get(`https://api.quran.com/api/v4/verses/by_chapter/${s}?language=${lang}&words=true&word_fields=text_indopak,text_uthmani&fields=qpc_uthmani_hafs,text_indopak_nastaleeq&per_page=50&page=${page}`);
    out.push(...d.verses);
    if (!d.pagination?.next_page) return out;
  }
}
/** Indo-Pak ayahs end in a font-specific token (۟ plus pause marks); the app draws its own ayah-end sign. */
const ipBody = t => t.replace(/\s*\u06DF\S*\s*$/u, '').trim();
/** Stop signs at the end of an ayah are part of that end token; keep them so the app can show them before its own end
 *  sign. Only real stop signs: the token also holds parts of the marker's own design (۠ ۪ ۫ ۥ) and the font's private glyphs. */
const STOP = /[\u0614-\u0617\u065A\u06D6-\u06DC\u06E2]/gu;
const ipStop = t => (t.match(/\u06DF(\S*)\s*$/u)?.[1].match(STOP) ?? []).join('');
/** Word texts can end in a right-to-left mark or the font's private-use end glyph. */
const clean = t => (t || '').replace(/[‏-]/gu, '').trim();

const file = s => path.join(OUT, 'surah', `${s}.dat`);
for (const s of SURAHS){
  if (fs.existsSync(file(s))) continue;
  const [en, ur, tr] = await Promise.all([verses(s, 'en'), verses(s, 'ur'), get(`https://api.alquran.cloud/v1/surah/${s}/editions/ur.jalandhry,en.sahih`)]);
  const [jal, sahih] = tr.data;
  const ayahs = en.map((v, i) => ({
    a: v.verse_number, n: v.id, p: v.page_number, j: v.juz_number,
    ip: ipBody(v.text_indopak_nastaleeq), ...(ipStop(v.text_indopak_nastaleeq) && {ipStop: ipStop(v.text_indopak_nastaleeq)}), uth: v.qpc_uthmani_hafs,
    ur: jal.ayahs[i].text, en: sahih.ayahs[i].text,
    w: v.words.filter(w => w.char_type_name === 'word').map((w, k) => {
      const u = ur[i].words.filter(x => x.char_type_name === 'word')[k];
      return {ip: clean(w.text_indopak), tr: w.transliteration?.text || '', en: w.translation?.text || '', ur: u?.translation?.text || ''};
    }),
  }));
  fs.writeFileSync(file(s), JSON.stringify({s, ayahs}));
  fs.copyFileSync(path.join(ROOT, 'data/morph', `${s}.json`), path.join(OUT, 'morph', `${s}.dat`));
  console.log(s, ayahs.length);
}

// Index: each Mushaf page as [surah, first ayah, last ayah] runs, the first ayah of each juz
const pages = [], juz = [];
for (const s of SURAHS){
  for (const {a, p, j} of JSON.parse(fs.readFileSync(file(s), 'utf8')).ayahs){
    const runs = pages[p - 1] ??= [], last = runs[runs.length - 1];
    if (last && last[0] === s && last[2] === a - 1) last[2] = a; else runs.push([s, a, a]);
    juz[j - 1] ??= [s, a];
  }
}
fs.writeFileSync(path.join(OUT, 'index.json'), JSON.stringify({pages, juz}));
fs.copyFileSync(file(1), path.join(OUT, 'fatihah.json'));
// Search reads only each ayah's Arabic, Urdu and English: [surah, ayah, Indo-Pak, Urdu, English]
const rows = SURAHS.flatMap(s => JSON.parse(fs.readFileSync(file(s), 'utf8')).ayahs.map(x => [s, x.a, x.ip, x.ur, x.en]));
fs.writeFileSync(path.join(OUT, 'search.dat'), JSON.stringify(rows));
console.log('pages', pages.length, 'juz', juz.length);

// Metro needs literal require()s, so the file list is generated
const req = d => SURAHS.map(s => `  ${s}: require('@/assets/quran/${d}/${s}.dat'),`).join('\n');
fs.writeFileSync(path.resolve('src/lib/quran-files.ts'), `/** Generated by scripts/fetch-quran.mjs: the asset file of each surah and of its grammar. */
/* eslint-disable @typescript-eslint/no-require-imports -- Metro bundles assets only from literal require()s */
export const SURAH_FILES: Record<number, number> = {
${req('surah')}
};
export const MORPH_FILES: Record<number, number> = {
${req('morph')}
};
export const SEARCH_FILE: number = require('@/assets/quran/search.dat');
`);

// Surah list from the site's built-in table: [Arabic name, English name, meaning, ayahs, revelation]
const src = fs.readFileSync(path.join(ROOT, 'lib/surahs.ts'), 'utf8');
const str = String.raw`"((?:[^"\\]|\\.)*)"`, un = t => t.replace(/\\"/g, '"');
const list = [...src.matchAll(new RegExp(String.raw`\[${str},${str},${str},(\d+),"(\w+)"\]`, 'g'))].map((m, i) => ({n: i + 1, ar: un(m[1]), en: un(m[2]), meaning: un(m[3]), ayahs: +m[4], rev: m[5]}));
fs.writeFileSync(path.join(OUT, 'surahs.json'), JSON.stringify(list));
console.log('surahs', list.length);
